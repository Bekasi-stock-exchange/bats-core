-- Allow an explicitly supplied orders.id.
--
-- An order id must be known before matching, because the trades produced by a
-- match reference it as a foreign key. The order row itself can only be written
-- after matching, once its sequence number and final state are decided. So the
-- application reserves an id from this column's identity sequence with nextval()
-- and supplies it on insert.
--
-- GENERATED ALWAYS rejects a supplied value; BY DEFAULT accepts one and still
-- auto-assigns when it is omitted. Re-running this statement is harmless.
ALTER TABLE orders ALTER COLUMN id SET GENERATED BY DEFAULT;
